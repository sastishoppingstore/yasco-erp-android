#!/usr/bin/env python3
"""Patch the generated Android project for the YASCO ERP build.

`tauri android init` regenerates `src-tauri/gen/android` from a template, so
every change the app needs is applied here, idempotently, right after init:

1. `AndroidManifest.xml`
   * `INTERNET` permission (the API is reached over https),
   * `usesCleartextTraffic` + an explicit `networkSecurityConfig` so the local
     engine is reachable even on ROMs that ignore the cleartext shorthand.

2. `build.gradle.kts`
   * `compileSdk` / `targetSdk` 35 (Play requirement),
   * `versionCode` from `BUILD_VERSION_CODE` when the CI provides one.

3. `MainActivity.kt`
   * `handleBackNavigation = true`. Tauri ships it as `false`, which makes the
     hardware back button close the app from anywhere, including three screens
     deep inside the ERP. With `true`, wry walks the WebView history first
     (React Router pushes real history entries) and only closes the app when
     there is nothing left to go back to.

4. Launcher icons
   * copy the 3D brand icons generated by `npx tauri icon` into the project.

5. Splash screen
   * a native `windowBackground` layer-list (brand gradient + logo) so the app
     never flashes white while the WebView boots.
"""

from __future__ import annotations

import os
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAIN = ROOT / "src-tauri" / "gen" / "android" / "app" / "src" / "main"
RES = MAIN / "res"
ICONS = ROOT / "src-tauri" / "icons" / "android"
GRADLE = ROOT / "src-tauri" / "gen" / "android" / "app" / "build.gradle.kts"


def patch_manifest() -> str:
    path = MAIN / "AndroidManifest.xml"
    if not path.exists():
        sys.exit(f"missing {path}")
    text = path.read_text(encoding="utf-8")
    original = text

    if "usesCleartextTraffic" not in text:
        text = re.sub(
            r"<application\b",
            '<application android:usesCleartextTraffic="true"',
            text,
            count=1,
        )

    # Explicit network security config: some Android Go / OEM ROMs ignore the
    # `usesCleartextTraffic` shorthand and otherwise block the loopback engine.
    if "networkSecurityConfig" not in text:
        text = re.sub(
            r"<application\b",
            '<application android:networkSecurityConfig="@xml/network_security_config"',
            text,
            count=1,
        )

    if "android.permission.INTERNET" not in text:
        text = text.replace(
            "<application",
            '<uses-permission android:name="android.permission.INTERNET"/>\n    <application',
            1,
        )

    if text != original:
        path.write_text(text, encoding="utf-8")
    cleartext = "usesCleartextTraffic" in text
    internet = "android.permission.INTERNET" in text
    nsc = "networkSecurityConfig" in text
    return f"manifest: cleartext={cleartext} internet={internet} nsc={nsc}"


def patch_network_security() -> str:
    """Allow cleartext to the app's own loopback engine on every ROM.

    The custom-scheme engine needs no cleartext at all, but the loopback
    fallback talks to `http://127.0.0.1`. Keeping the config explicit avoids the
    handful of OEM ROMs (mostly Go edition) that ignore `usesCleartextTraffic`.
    """
    xml = RES / "xml" / "network_security_config.xml"
    xml.parent.mkdir(parents=True, exist_ok=True)
    xml.write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="true">127.0.0.1</domain>
        <domain includeSubdomains="true">localhost</domain>
        <domain includeSubdomains="true">yasco.tech</domain>
    </domain-config>
</network-security-config>
""",
        encoding="utf-8",
    )
    return "network security: cleartext allowed for loopback + yasco.tech"


BACK_NAV = """
    // Hardware back walks the WebView history (React Router routes) instead of
    // closing the app. When no history is left, wry falls back to the default
    // behaviour and the activity finishes.
    override val handleBackNavigation: Boolean = true
"""


def patch_main_activity() -> str:
    candidates = sorted(MAIN.rglob("MainActivity.kt"))
    if not candidates:
        candidates = sorted(MAIN.rglob("MainActivity.java"))
    if not candidates:
        sys.exit("MainActivity not found in src-tauri/gen/android")

    path = candidates[0]
    text = path.read_text(encoding="utf-8")

    if "handleBackNavigation" in text:
        return f"{path.name}: back navigation already enabled"

    pattern = re.compile(r"(class\s+MainActivity\s*(?::\s*[A-Za-z0-9_.]+\(\s*\))?\s*\{)")
    match = pattern.search(text)
    if not match:
        sys.exit(f"cannot find MainActivity class declaration in {path}")

    inserted = text[: match.start()] + match.group(1) + "\n" + BACK_NAV + text[match.end():]
    path.write_text(inserted, encoding="utf-8")
    return f"{path.name}: back navigation enabled"


def patch_gradle() -> str:
    if not GRADLE.exists():
        sys.exit(f"missing {GRADLE}")
    text = GRADLE.read_text(encoding="utf-8")
    original = text

    text = re.sub(r"compileSdk\s*=\s*\d+", "compileSdk = 35", text, count=1)
    text = re.sub(r"targetSdk\s*=\s*\d+", "targetSdk = 35", text, count=1)

    code = os.environ.get("BUILD_VERSION_CODE", "").strip()
    if code.isdigit():
        text = re.sub(r"versionCode\s*=\s*\d+", f"versionCode = {code}", text, count=1)

    if text != original:
        GRADLE.write_text(text, encoding="utf-8")

    minsdk = re.search(r"minSdk\s*=\s*(\d+)", text)
    targetsdk = re.search(r"targetSdk\s*=\s*(\d+)", text)
    versioncode = re.search(r"versionCode\s*=\s*(\d+)", text)
    return (
        "gradle: minSdk={} targetSdk={} versionCode={}".format(
            minsdk.group(1) if minsdk else "?",
            targetsdk.group(1) if targetsdk else "?",
            versioncode.group(1) if versioncode else "?",
        )
    )


def copy_icons() -> str:
    if not ICONS.exists():
        return "icons: source directory missing (skipped)"
    copied = 0
    for src in ICONS.rglob("*"):
        if src.is_dir():
            continue
        rel = src.relative_to(ICONS)
        dst = RES / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        copied += 1
    return f"icons: copied {copied} files"


SPLASH_LOGO = ROOT / "assets" / "branding" / "splash-512.png"


def patch_splash() -> str:
    if not SPLASH_LOGO.exists():
        return "splash: artwork missing (skipped)"

    drawable = RES / "drawable-nodpi"
    drawable.mkdir(parents=True, exist_ok=True)
    shutil.copy2(SPLASH_LOGO, drawable / "ys_splash_logo.png")

    splash_xml = RES / "drawable" / "ys_splash.xml"
    splash_xml.parent.mkdir(parents=True, exist_ok=True)
    splash_xml.write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item>
        <shape android:shape="rectangle">
            <gradient
                android:angle="270"
                android:startColor="#1b3563"
                android:centerColor="#0b1730"
                android:endColor="#04070f"
                android:type="linear" />
        </shape>
    </item>
    <item
        android:width="170dp"
        android:height="170dp"
        android:gravity="center">
        <bitmap
            android:src="@drawable/ys_splash_logo"
            android:gravity="fill"
            android:mipMap="true" />
    </item>
</layer-list>
""",
        encoding="utf-8",
    )

    themes = sorted(RES.glob("values*/themes.xml")) + sorted(RES.glob("values*/styles.xml"))
    if not themes:
        return "splash: drawable written, but no themes.xml found"

    patched = []
    for path in themes:
        text = path.read_text(encoding="utf-8")
        original = text
        if "<item name=\"android:windowBackground\">" in text:
            text = re.sub(
                r'<item name="android:windowBackground">.*?</item>',
                '<item name="android:windowBackground">@drawable/ys_splash</item>',
                text,
                count=1,
            )
        elif "</style>" in text:
            text = text.replace(
                "</style>",
                '    <item name="android:windowBackground">@drawable/ys_splash</item>\n</style>',
                1,
            )
        if "android:statusBarColor" not in text and "</style>" in text:
            text = text.replace(
                "</style>",
                '    <item name="android:statusBarColor">#0b1730</item>\n'
                '    <item name="android:navigationBarColor">#0b1730</item>\n'
                "</style>",
                1,
            )
        if text != original:
            path.write_text(text, encoding="utf-8")
            patched.append(path.parent.name)
    return "splash: " + (", ".join(patched) if patched else "already applied")


def main() -> None:
    print(patch_manifest())
    print(patch_network_security())
    print(patch_gradle())
    print(patch_main_activity())
    print(copy_icons())
    print(patch_splash())


if __name__ == "__main__":
    main()